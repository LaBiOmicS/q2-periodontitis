"""Formats the result tables as Markdown (<results_dir>/REPORT.md).

    python -I report.py <results_dir>

Every number in REPORT.md is read from <results_dir>/tables/*.tsv or
<results_dir>/qc.tsv; nothing is typed by hand.
"""
import os
import sys

import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from common import PRIMARY_CLASSIFIER, load_cohorts  # noqa: E402

results = sys.argv[1]
tables = os.path.join(results, "tables")
cohorts = load_cohorts().set_index("cohort")
NAMES = {"SMDI": "SMDI", "SMDI_simplified": "SMDI_simplified",
         "PC2014_moderate": "PC2014_moderate"}
lines = []


def read(name, base=tables):
    try:
        return pd.read_csv(os.path.join(base, name), sep="\t")
    except (FileNotFoundError, pd.errors.EmptyDataError):
        return pd.DataFrame()


def f(x, d=2):
    if pd.isna(x):
        return "–"
    return ("%%.%df" % d) % x


def p(x):
    if pd.isna(x):
        return "–"
    return "%.2g" % x if x >= 1e-3 else "%.1e" % x


def name(m):
    return NAMES.get(m, m.replace("complex_", "") + " complex")


def table(header, rows):
    lines.append("| " + " | ".join(header) + " |")
    lines.append("|" + "---|" * len(header))
    for r in rows:
        lines.append("| " + " | ".join(str(x) for x in r) + " |")
    lines.append("")


def h(text, level=2):
    lines.extend(["#" * level + " " + text, ""])


lines.extend(["# Validation results", "",
              "Generated by `validation/analysis/report.py` from "
              "`validation/results/tables/`. Primary classifier: naive Bayes "
              "(`nb`); `vsearch` results are in the same tables.", ""])

qc = read("qc.tsv", results)
h("Cohorts and quality control")
rows = []
for r in qc[qc["processed"] == "yes"].itertuples():
    c = cohorts.loc[r.cohort]
    rows.append([r.cohort, r.classifier, c["region"], c["independent"],
                 int(r.samples), int(r.subjects), "%.0f" % r.median_depth,
                 f(r.median_reads_retained), f(r.median_assigned_fraction),
                 f(r.median_species_fraction), int(r.smdi_species_absent),
                 r.qc_flags if isinstance(r.qc_flags, str) else ""])
table(["Cohort", "Classifier", "Region", "Independent", "Samples",
       "Subjects", "Median depth", "Reads retained", "Assigned",
       "Named to species", "SMDI species absent", "QC flags"], rows)
missing = qc[qc["processed"] == "no"]["cohort"].unique()
if len(missing):
    lines.extend(["Not processed: " + ", ".join(missing) + ".", ""])

disc = read("discrimination.tsv")
for clf in ["nb", "vsearch"]:
    h("Q1. Health vs periodontitis, subject level (%s)" % clf)
    d = disc[disc["classifier"] == clf]
    rows = []
    for (cohort, m), r in d.set_index(["cohort", "measure"]).iterrows():
        rows.append([cohort, cohorts.loc[cohort, "independent"], name(m),
                     "%d / %d" % (r.n_health, r.n_periodontitis),
                     f(r.median_health, 3), f(r.median_periodontitis, 3),
                     "%s (%s–%s)" % (f(r.auc), f(r.ci_low), f(r.ci_high)),
                     p(r.p)])
    table(["Cohort", "Independent", "Measure", "n health / perio",
           "Median health", "Median perio", "AUC (95% CI)", "p"], rows)

meta = read("meta_auc.tsv")
h("Q1. Random-effects meta-analysis of AUC")
rows = []
for r in meta.itertuples():
    rows.append([r.set, r.classifier, name(r.measure), r.analysis, r.k,
                 "%s (%s–%s)" % (f(r.estimate), f(r.ci_low), f(r.ci_high)),
                 "%s–%s" % (f(r.pi_low), f(r.pi_high)), f(r.i2 * 100, 0),
                 "%.2g" % r.tau2])
table(["Set", "Classifier", "Measure", "Analysis", "k",
       "Pooled AUC (95% CI)", "95% PI", "I² (%)", "τ²"], rows)
loo = read("meta_auc_loo.tsv")
if not loo.empty:
    h("Q1. Leave-one-cohort-out, SMDI", 3)
    table(["Classifier", "Left out", "Pooled AUC (95% CI)", "I² (%)"],
          [[r.classifier, r.left_out, "%s (%s–%s)" % (
              f(r.estimate), f(r.ci_low), f(r.ci_high)), f(r.i2 * 100, 0)]
           for r in loo.itertuples()])

dl = read("delong.tsv")
h("Q2. SMDI vs Red complex (paired DeLong)")
table(["Cohort", "Classifier", "Measure", "AUC measure", "AUC Red",
       "Difference (SE)", "p", "q"],
      [[r.cohort, r.classifier, name(r.measure), f(r.auc_measure),
        f(r.auc_comparator), "%s (%s)" % (f(r.difference, 3), f(r.se, 3)),
        p(r.p), p(r.q)] for r in dl.itertuples()])
mdl = read("meta_delong.tsv")
if not mdl.empty:
    table(["Set", "Classifier", "Measure", "k",
           "Pooled difference vs Red (95% CI)", "p", "I² (%)"],
          [[r.set, r.classifier, name(r.measure), r.k,
            "%s (%s–%s)" % (f(r.estimate, 3), f(r.ci_low, 3),
                            f(r.ci_high, 3)), p(r.p), f(r.i2 * 100, 0)]
           for r in mdl.itertuples()])

cuts = read("cutoffs.tsv")
h("Q3. Published cut-offs (subjects)")
table(["Cohort", "Classifier", "Index > cut-off", "Sensitivity (95% CI)",
       "Specificity (95% CI)", "Accuracy"],
      [[r.cohort, r.classifier, "%s > %g" % (r.measure, r.cutoff),
        "%s (%s–%s)" % (f(r.sensitivity), f(r.sens_low), f(r.sens_high)),
        "%s (%s–%s)" % (f(r.specificity), f(r.spec_low), f(r.spec_high)),
        f(r.accuracy)] for r in cuts.itertuples()])
cp = read("cutoffs_pooled.tsv")
if not cp.empty:
    table(["Set", "Classifier", "Index > cut-off", "k",
           "Pooled sensitivity (95% CI)", "Pooled specificity (95% CI)"],
          [[r.set, r.classifier, "%s > %g" % (r.measure, r.cutoff), r.k,
            "%s (%s–%s)" % (f(r.sensitivity), f(r.sens_low),
                            f(r.sens_high)),
            "%s (%s–%s)" % (f(r.specificity), f(r.spec_low),
                            f(r.spec_high))] for r in cp.itertuples()])

th = read("therapy.tsv")
h("Q4. Change after therapy (follow-up minus baseline)")
th = th[th["classifier"] == PRIMARY_CLASSIFIER] if not th.empty else th
table(["Cohort", "Follow-up", "Arm", "Measure", "n", "Median change",
       "Decreased", "Rank-biserial r", "p", "q"],
      [[r.cohort, r.follow_up, r.arm, name(r.measure), r.n,
        f(r.median_change, 3), "%.0f%%" % (100 * r.fraction_decreased),
        f(r.rank_biserial), p(r.p), p(r.q)] for r in th.itertuples()])
arms = read("therapy_arms.tsv")
if not arms.empty:
    arms = arms[arms["classifier"] == PRIMARY_CLASSIFIER]
    table(["Cohort", "Follow-up", "Treated vs reference", "Measure",
           "n", "Median change treated", "Median change reference",
           "AUC (larger decrease)", "p", "q"],
          [[r.cohort, r.follow_up, "%s vs %s" % (r.treated, r.reference),
            name(r.measure), "%d / %d" % (r.n_treated, r.n_reference),
            f(r.median_change_treated, 3), f(r.median_change_reference, 3),
            f(r.auc_larger_decrease), p(r.p), p(r.q)]
           for r in arms.itertuples()])

pr = read("prognosis.tsv")
h("Q5. Baseline values and non-response")
table(["Cohort", "Classifier", "Measure", "n non-resp / resp",
       "AUC non-response (95% CI)", "p", "q"],
      [[r.cohort, r.classifier, name(r.measure),
        "%d / %d" % (r.n_nonresponders, r.n_responders),
        "%s (%s–%s)" % (f(r.auc_nonresponse), f(r.ci_low), f(r.ci_high)),
        p(r.p), p(r.q)] for r in pr.itertuples()])

cl = read("clinical.tsv")
h("Q6. Spearman correlation with clinical measures (%s)"
  % PRIMARY_CLASSIFIER)
cl = cl[cl["classifier"] == PRIMARY_CLASSIFIER] if not cl.empty else cl
table(["Cohort", "Clinical", "Measure", "n", "ρ", "p", "q"],
      [[r.cohort, r.clinical, name(r.measure), r.n, f(r.rho), p(r.p),
        p(r.q)] for r in cl.itertuples()])

h("Robustness")
ag = read("classifier_agreement.tsv")
h("Classifier agreement (nb vs vsearch, samples)", 3)
table(["Cohort", "Measure", "n", "Spearman ρ", "Median vsearch − nb (IQR)"],
      [[r.cohort, name(r.measure), r.n, f(r.spearman),
        "%s (%s to %s)" % (f(r.median_difference, 3), f(r.iqr_low, 3),
                           f(r.iqr_high, 3))] for r in ag.itertuples()])
rg = read("regions.tsv")
h("Same samples in two regions", 3)
table(["Regions", "Classifier", "Measure", "n", "Median 1", "Median 2",
       "Median shift (2 − 1)", "Wilcoxon p", "Spearman ρ", "AUC 1",
       "AUC 2"],
      [["%s → %s" % (r.region_1, r.region_2), r.classifier, name(r.measure),
        r.n_samples, f(r.median_1), f(r.median_2),
        f(r.median_shift_2_minus_1), p(r.wilcoxon_p), f(r.spearman),
        f(r.auc_1), f(r.auc_2)] for r in rg.itertuples()])
eps = read("robustness_epsilon.tsv")
h("Pseudocount", 3)
cols = [c for c in eps.columns if c.startswith(("sens_", "spec_"))]
table(["Cohort", "Classifier", "Measure", "ε", "AUC", "ρ vs original",
       "Median shift"] + cols,
      [[r["cohort"], r["classifier"], r["measure"], r["epsilon"],
        f(r["auc"]), f(r["spearman_vs_original"], 3),
        f(r["median_shift_vs_original"])] + [f(r[c]) for c in cols]
       for _, r in eps.iterrows()])
rar = read("robustness_rarefaction.tsv")
h("Rarefaction (mean of 10 draws)", 3)
if not rar.empty:
    s = rar.groupby(["cohort", "classifier", "measure", "depth"]).agg(
        auc=("auc", "mean"), sd=("auc", "std"),
        base=("auc_unrarefied", "first"), n_h=("n_health", "first"),
        n_p=("n_periodontitis", "first")).reset_index()
    table(["Cohort", "Classifier", "Measure", "Depth", "n health / perio",
           "Mean AUC (SD)", "Unrarefied AUC"],
          [[r.cohort, r.classifier, name(r.measure), r.depth,
            "%d / %d" % (r.n_h, r.n_p), "%s (%s)" % (f(r.auc), f(r.sd, 3)),
            f(r.base)] for r in s.itertuples()])

with open(os.path.join(results, "REPORT.md"), "w") as fh:
    fh.write("\n".join(lines) + "\n")
print("REPORT.md written")
